"""The slowest application queries by mean time, with their plans.

    python infra/perf/slow_queries.py [--top 20] [--out docs/db_tuning_plans.md]

Reads pg_stat_statements (needs `shared_preload_libraries = 'pg_stat_statements'`, which dev_cluster.sh sets), so run a
load first. Plans are generic plans (`EXPLAIN (GENERIC_PLAN)`, parameters unknown) taken as the restricted application
role with a tenant context, so Row Level Security conditions are part of what is shown.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "apps" / "api"))

from meridian.db import connect  # noqa: E402

SKIP = re.compile(
    r"^\s*(set|begin|commit|rollback|show|deallocate|explain|create|alter|drop|analyze|vacuum|copy|listen|notify"
    r"|select set_config)\b",
    re.I,
)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--top", type=int, default=20)
    ap.add_argument("--min-calls", type=int, default=5)
    ap.add_argument("--out", type=Path, default=Path("docs/db_tuning_plans.md"))
    args = ap.parse_args()
    conn = connect()
    rows = conn.execute(
        """SELECT calls, mean_exec_time, max_exec_time, total_exec_time, rows, shared_blks_hit, shared_blks_read, query
             FROM pg_stat_statements
            WHERE dbid = (SELECT oid FROM pg_database WHERE datname = current_database()) AND calls >= %s
              AND query NOT ILIKE '%%pg_stat_statements%%' AND query NOT ILIKE '%%pg_catalog%%'
            ORDER BY mean_exec_time DESC""",
        (args.min_calls,),
    ).fetchall()
    chosen = [r for r in rows if not SKIP.match(r[7])][: args.top]
    tenant = conn.execute("SELECT id FROM tenants WHERE slug = 'perf-large'").fetchone()
    lines = [
        "# Slowest application queries",
        "",
        "Generated by `infra/perf/slow_queries.py` from pg_stat_statements after the load test in `docs/perf.md`.",
        "Times are server side. Plans are generic plans taken as the application role with a tenant context.",
        "",
        "| # | mean ms | max ms | calls | total s | rows per call | query |",
        "|--:|--:|--:|--:|--:|--:|---|",
    ]
    for i, (calls, mean, mx, total, nrows, _hit, _read, query) in enumerate(chosen, 1):
        short = " ".join(query.split())[:110].replace("|", "\\|")
        lines.append(
            f"| {i} | {mean:.2f} | {mx:.1f} | {calls} | {total / 1000:.1f} | {nrows / calls:.0f} | `{short}` |"
        )
    lines.append("")
    for i, (_c, mean, _m, _t, _r, _h, _rd, query) in enumerate(chosen, 1):
        lines += [f"## {i}. mean {mean:.2f} ms", "", "```sql", " ".join(query.split()), "```", ""]
        try:
            conn.execute("BEGIN")
            conn.execute("SET LOCAL ROLE meridian_app")
            conn.execute(
                "SELECT set_config('app.tenant_id', %s, true), set_config('app.role', 'manager', true), "
                "set_config('app.bypass', 'off', true)",
                (str(tenant[0]) if tenant else "",),
            )
            plan = conn.execute("EXPLAIN (GENERIC_PLAN, COSTS OFF) " + query).fetchall()
            lines += ["```", *(r[0] for r in plan), "```", ""]
        except Exception as exc:  # noqa: BLE001 - a plan that cannot be explained generically is reported, not fatal
            lines += [f"Plan not available: {str(exc).splitlines()[0]}", ""]
        finally:
            conn.rollback()
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} with {len(chosen)} queries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
