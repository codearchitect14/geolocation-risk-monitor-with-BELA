"""Render docs/place_kb_report.md from data/processed/place_kb_report.json and query plan timings."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[4]
JSON_PATH = ROOT / "data" / "processed" / "place_kb_report.json"
OUT_PATH = ROOT / "docs" / "place_kb_report.md"


def table(headers: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def render(report: dict[str, Any]) -> str:
    q, ev = report["quality"], report.get("search_eval") or {}
    if ev:
        ev.setdefault("vectors", {"skipped": "not evaluated in this run"})
    cross = q["cross_links"]
    out = [
        "# Place knowledge base report",
        "",
        "Generated by `make etl-quality`. Figures describe the development database built from the data in",
        "`data/raw` at that time; see the scope notes before comparing them with the plan targets.",
        "",
        "## Scope of this build",
        "",
        "- GeoNames: settlements with population of at least 1,000, administrative divisions, and facility types",
        "  (minor dams, bridges, and tunnels excluded).",
        "- Wikidata: a **partial** subset built from the first six million lines of the entity dump, with the class",
        "  hierarchy expanded through the Wikidata Query Service. A full pass over the 103 GB dump has not been run.",
        "  Wikidata counts and cross-link coverage below are therefore lower bounds on what a full build gives.",
        "- Natural Earth 10m country and admin-1 polygons.",
        "",
        "## Contents",
        "",
        f"Total places: **{q['places_total']:,}**",
        "",
        table(["Source", "Places"], [[k, f"{v:,}"] for k, v in q["by_source"].items()]),
        "",
        table(
            ["Type", "Places", "With QID", "With GeoNames ID"],
            [
                [r["type"], f"{r['places']:,}", f"{r['with_qid']:,}", f"{r['with_geonames_id']:,}"]
                for r in q["cross_links_by_type"]
            ],
        ),
        "",
        "## Cross-link coverage",
        "",
        table(
            ["Measure", "Value"],
            [
                [
                    "GeoNames records loaded here that match a Wikidata entity",
                    f"{cross['geonames_subset_with_qid']:,} of {cross['geonames_subset_total']:,} ({pct(cross['geonames_subset_qid_coverage'])})",
                ],
                [
                    "Places with a GeoNames ID that carry a QID (includes Wikidata-only places citing GeoNames IDs outside this subset)",
                    f"{cross['geonames_places_with_qid']:,} of {cross['geonames_places_total']:,} ({pct(cross['geonames_qid_coverage'])})",
                ],
                [
                    "Wikidata places that carry a GeoNames ID",
                    f"{cross['wikidata_places_with_geonames_id']:,} of {cross['wikidata_places_total']:,} ({pct(cross['wikidata_geonames_coverage'])})",
                ],
                ["Merged through P1566", f"{cross['merged_by_p1566']:,}"],
                ["Merged through name, country, and proximity", f"{cross['merged_by_name_country_proximity']:,}"],
                ["Wikidata-only places", f"{cross['wikidata_without_geonames_link']:,}"],
            ],
        ),
        "",
        "Merge conflicts written to the review list:",
        "",
        table(["Reason", "Count"], [[k, f"{v:,}"] for k, v in q["merge_review"].items()])
        if q["merge_review"]
        else "None.",
        "",
        "## Data quality checks",
        "",
        table(
            ["Check", "Violations", "Kind"],
            [[k, f"{v:,}", "hard" if k in HARD else "flag"] for k, v in q["checks"].items()],
        ),
        "",
        f"Hard failures: **{len(q['hard_failures'])}**. Flags are reported for review and do not fail the build.",
        f"Pandera schema check on a random sample of {q['pandera_sample']['rows']:,} places: "
        f"{'passed' if q['pandera_sample']['valid'] else 'FAILED'}.",
        "",
        "## Aliases and embeddings",
        "",
        f"Aliases: {q['aliases']['total']:,} (mean {q['aliases']['mean_per_place']} per place; "
        f"{q['aliases']['places_with_alias']:,} places have at least one).",
        "",
        table(["Language", "Aliases"], [[k, f"{v:,}"] for k, v in q["aliases"]["by_language"].items()]),
        "",
        f"Embeddings: {q['embeddings']['rows']:,} rows for {q['embeddings']['places']:,} places "
        f"({', '.join(f'{k}: {v:,}' for k, v in q['embeddings']['by_kind'].items()) or 'none yet'}).",
    ]
    if ev and "error" not in ev:
        out += [
            "",
            "## Name search evaluation",
            "",
            f"Sample: {ev['sample_size']:,} (surface form, GeoNames ID) pairs drawn with a fixed seed from the EUPEG corpora LGL,",
            f"TR-News, and GeoWebNews. {ev['gold_pairs_in_knowledge_base']:,} of {ev['gold_pairs_total']:,} gold pairs "
            f"({pct(ev['gold_kb_coverage'])}) have their place in the knowledge base; the rest are excluded from the sample.",
            "Queries carry no context (no country hint), which is the hardest setting.",
            "",
            table(
                ["Measure", "Value"],
                [
                    ["Top-5 accuracy", pct(ev["top5"])],
                    ["Target (top-5)", pct(ev["target_top5"])],
                    ["Target met", "yes" if ev["target_met"] else "**no**"],
                    ["Top-1 accuracy", pct(ev["top1"])],
                    ["Baseline: most populous exact match, top-1", pct(ev["baseline_most_populous_exact_top1"])],
                    ["Top-5 on ambiguous names", f"{pct(ev['top5_ambiguous_names'])} (n={ev['ambiguous_sample']})"],
                    ["Latency p50 / p95", f"{ev['latency_ms'].get('p50')} ms / {ev['latency_ms'].get('p95')} ms"],
                ],
            ),
            "",
            "Vector retrieval (bge-m3 over the stored name, alias, and description texts):",
            "",
            (
                table(
                    ["Measure", "Value"],
                    [
                        ["Vector only, top-1", pct(ev["vectors"].get("vector_only_top1"))],
                        ["Vector only, top-5", pct(ev["vectors"].get("vector_only_top5"))],
                        [
                            "Top 3 of trigram search plus vector candidates, top-5",
                            pct(ev["vectors"].get("hybrid_top5")),
                        ],
                    ],
                )
                if "skipped" not in ev["vectors"]
                else f"Not evaluated: {ev['vectors']['skipped']}."
            ),
            "",
            table(["Corpus", "Top-5"], [[k, pct(v)] for k, v in ev["top5_by_corpus"].items()]),
            "",
            table(["Gold place type", "Top-5"], [[k, pct(v)] for k, v in ev["top5_by_type"].items()]),
            "",
            "Sample misses:",
            "",
            table(
                ["Surface", "Expected type", "Returned (top 3)"],
                [[m["surface"], m["expected_type"], "; ".join(m["returned"])] for m in ev["sample_misses"][:15]],
            ),
        ]
    out += ["", "Query plans and latency: see `docs/query_plans.md`.", ""]
    return "\n".join(out)


HARD = {
    "invalid_coordinates",
    "centroid_differs_from_lat_lon",
    "unknown_country_code",
    "missing_type",
    "duplicate_qid",
    "duplicate_geonames_id",
    "missing_uncertainty",
    "missing_h3",
    "missing_bbox",
    "hierarchy_cycles",
    "wrong_vector_dimension",
}


def main() -> int:
    report = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    OUT_PATH.write_text(render(report), encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
